import express from 'express';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json({ limit: '10mb' }));

// Server-side Gemini API client
let ai: GoogleGenAI | null = null;
if (process.env.GEMINI_API_KEY) {
  ai = new GoogleGenAI({
    apiKey: process.env.GEMINI_API_KEY,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });
}

// In-memory audio cache for instant playback of repeated words/phonemes
const audioCache = new Map<string, string>();

// API route for AI Vietnamese Text-to-Speech
app.post('/api/tts', async (req, res) => {
  try {
    const { text, style } = req.body;
    if (!text || typeof text !== 'string') {
      return res.status(400).json({ error: 'Text is required' });
    }

    const trimmedText = text.trim();
    const cacheKey = `${trimmedText}_${style || 'default'}`;

    if (audioCache.has(cacheKey)) {
      return res.json({
        audioBase64: audioCache.get(cacheKey),
        cached: true,
      });
    }

    if (!ai) {
      return res.status(503).json({
        error: 'Gemini API not configured. Using client-side speech synthesis.',
        fallback: true,
      });
    }

    // The text field in Gemini TTS is the exact speech content to synthesize
    const voiceStyle = style || 'A gentle, warm Vietnamese female teacher speaking slowly, accurately and clearly for first grade children';
    
    let audioBase64: string | undefined;

    // Primary flagship TTS model: gemini-3.8-flash-tts with Kore voice
    try {
      const response = await ai.models.generateContent({
        model: 'gemini-3.8-flash-tts',
        contents: [
          {
            role: 'user',
            parts: [
              {
                text: trimmedText,
                speechMetadata: {
                  style: voiceStyle,
                },
              },
            ],
          },
        ],
        config: {
          responseModalities: ['AUDIO'],
          speechConfig: {
            voiceConfig: {
              prebuiltVoiceConfig: { voiceName: 'Kore' },
            },
          },
        },
      });
      audioBase64 = response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;
    } catch (primaryErr: any) {
      console.warn('Primary TTS (gemini-3.8-flash-tts) error, attempting flash-lite-tts:', primaryErr?.message);
      // Secondary TTS model fallback
      try {
        const responseLite = await ai.models.generateContent({
          model: 'gemini-3.8-flash-lite-tts',
          contents: [
            {
              role: 'user',
              parts: [
                {
                  text: trimmedText,
                  speechMetadata: {
                    style: voiceStyle,
                  },
                },
              ],
            },
          ],
          config: {
            responseModalities: ['AUDIO'],
            speechConfig: {
              voiceConfig: {
                prebuiltVoiceConfig: { voiceName: 'Kore' },
              },
            },
          },
        });
        audioBase64 = responseLite.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;
      } catch (liteErr: any) {
        console.error('All Gemini TTS models failed:', liteErr?.message);
      }
    }

    if (!audioBase64) {
      return res.status(500).json({
        error: 'No audio generated by model',
        fallback: true,
      });
    }

    // Store in cache (limit max 500 items to avoid memory leak)
    if (audioCache.size > 500) {
      const firstKey = audioCache.keys().next().value;
      if (firstKey) audioCache.delete(firstKey);
    }
    audioCache.set(cacheKey, audioBase64);

    return res.json({
      audioBase64,
      cached: false,
    });
  } catch (error: any) {
    console.error('TTS API error:', error?.message || error);
    return res.status(500).json({
      error: error?.message || 'Failed to generate speech',
      fallback: true,
    });
  }
});

// Setup Vite middlewares in development or serve static in production
async function startServer() {
  const isProd = process.env.NODE_ENV === 'production';

  if (!isProd) {
    const { createServer } = await import('vite');
    const vite = await createServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(__dirname, 'dist', 'index.html'));
    });
  }

  app.listen(PORT, () => {
    console.log(`Server listening on http://localhost:${PORT}`);
  });
}

startServer();
